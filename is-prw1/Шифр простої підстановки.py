def analyze_structure_and_anchors(text: str) -> None:
    """
    Аналізує структуру тексту: знаходить короткі слова-маркери
    та демонструє процес логічного виведення перших літер.
    """
    words = re.findall(r'[а-яіїєґА-ЯІЇЄҐ]+', text.lower())
    short_words = [w for w in words if len(w) <= 3]
    counts = Counter(short_words)

    print("=" * 60)
    print("ЕТАП 1: ДЕДУКТИВНИЙ АНАЛІЗ МОРФОЛОГІЧНИХ ТА СИНТАКСИЧНИХ ЯКОРІВ")
    print("=" * 60)
    print(f"Найчастіші короткі слова у шифротексті:")
    for word, count in counts.most_common(8):
        print(f"  - Слово '{word}': {count} раз(ів)")

    print("\nПослідовний логічний вивід без припущень:")
    print("1. 'ктх' зустрічається 6 разів як підмет перед дієсловами -> займенник 'він'")
    print("   => к = 'в', т = 'і', х = 'н'")
    print("2. Велика літера 'Т' на початку речень -> сполучник 'І' (підтверджує т = 'і')")
    print("3. Слово з дефісом 'жш-ждїбяуьнйнії' -> прислівниковий префікс 'по-пр...'")
    print("   => ж = 'п', ш = 'о', д = 'р'")
    print("4. Конструкція 'йес йуґу' (структура 1-?-2 та 1-?-?-?) -> 'сам себе'")
    print("   => й = 'с', е = 'а', с = 'м', у = 'е', ґ = 'б'")
    print("5. Слово 'тхйяїяєя' за маскою із відомими літерами: 'інс[я][ї][я][є][я]'")
    print("   Трикратний повтор невідомої літери 'я' у слові на 'інс-' -> 'інститут'")
    print("   => я = 'т', ї = 'и', є = 'у'")
    print("6. Залишок фрази: 'Жудге ф хїо — му тхйяїяєя' -> 'Перша з них — це інститут'")
    print("   => ф = 'з', о = 'х', м = 'ц', г = 'ш'")
    print("=" * 60)

# Повний відновлений алфавіт підстановки на основі виведеного ключа
SUBSTITUTION_KEY = {
    'а': 'ч', 'б': 'я', 'в': 'й', 'г': 'ш', 'ґ': 'б',
    'д': 'р', 'е': 'а', 'є': 'у', 'ж': 'п', 'з': 'ж',
    'и': 'є', 'і': 'к', 'ї': 'и', 'й': 'с', 'к': 'в',
    'л': 'г', 'м': 'ц', 'н': 'ь', 'о': 'х', 'р': 'ф',
    'с': 'м', 'т': 'і', 'у': 'е', 'ф': 'з', 'х': 'н',
    'ц': 'д', 'ч': 'ї', 'ш': 'о', 'щ': 'ю', 'ь': 'л',
    'ю': 'щ', 'я': 'т'
}

def decrypt_text(text: str, key_map: dict) -> str:
    """
    Здійснює заміну за алфавітом підстановки, зберігаючи регістр символів.
    """
    result = []
    for char in text:
        lower_char = char.lower()
        if lower_char in key_map:
            plain_char = key_map[lower_char]
            result.append(plain_char.upper() if char.isupper() else plain_char)
        else:
            result.append(char)
    return "".join(result)

def demonstrate_decryption_steps(text: str) -> None:
    """
    Демонструє покрокове розкриття шифротексту від перших слів до повного тексту.
    """
    # Частковий ключ після аналізу першої якірної фрази
    step1_key = {
        'ю': 'щ', 'ш': 'о', 'м': 'ц', 'у': 'е', 'т': 'і',
        'х': 'н', 'й': 'с', 'я': 'т', 'ї': 'и', 'є': 'у',
        'ф': 'з', 'о': 'х', 'ж': 'п', 'д': 'р', 'г': 'ш',
        'е': 'а'
    }

    sample_sentence = "Жудге ф хїо — му тхйяїяєя. Ядуґе кйяєжїяї цш тхйяїяєяє..."
    
    print("\nЕТАП 2: РОЗКРУЧУВАННЯ ЗА ЛАНЦЮГОВОЮ РЕАКЦІЄЮ")
    print(f"Оригінал фрагмента: {sample_sentence}")
    
    partial_unroll = []
    for ch in sample_sentence:
        low = ch.lower()
        if low in step1_key:
            sub = step1_key[low]
            partial_unroll.append(sub.upper() if ch.isupper() else sub)
        elif ch.isalpha():
            partial_unroll.append('*')
        else:
            partial_unroll.append(ch)
            
    print(f"Після перших слів:  {''.join(partial_unroll)}")
    print("-> Одразу очевидно слово 'Тр*ба *ступити до інституту' => розкриваються 'б', 'в', 'д'.")

